export function getWorldName(world: WorldId): string {
  switch (world) {
    case 1:
      return 'Green Jungle';
    case 2:
      return 'Desert Kingdom';
    case 3:
      return 'Snow Mountain';
    case 4:
      return 'Dark Castle';
    case 5:
      return "Villain's Secret Island";
  }
}

export function getVillainForLevelEnd(levelId: number): VillainHeliConfig {
  const index = Math.max(0, Math.min(VILLAIN_SEEDS.length - 1, levelId - 1));
  const seed = VILLAIN_SEEDS[index];
  return {
    levelFrom: levelId,
    nextLevel: levelId + 1,
    villainName: seed.name,
    villainTitle: seed.title,
    heliName: seed.heliName,
    heliColor: seed.heliColor,
    heliAccent: seed.heliAccent,
    heliStyle: seed.heliStyle,
    captureMethod: seed.captureMethod,
    cameraAngle: seed.cameraAngle,
    tauntLine: seed.taunt,
    nextLocationClue: seed.clue,
    villainSkinTone: '#d6a483',
    villainCoatColor: seed.coat,
    villainVisorColor: seed.visor,
    villainHairStyle: seed.hair,
  };
}
